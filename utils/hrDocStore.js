import fs from "fs";
import path from "path";
import { S3Client, PutObjectCommand, GetObjectCommand, DeleteObjectCommand } from "@aws-sdk/client-s3";

// Where HR employee documents are kept. They are never public: the HR app streams them through the API
// after checking who is asking.
//   s3     the AWS bucket (AWS_BUCKET), under hr-documents/ — used when AWS keys are set
//   local  a private folder on this server (HR_DOCS_DIR, default ./private_uploads/hr-docs) — for localhost
export const docStorage = () => process.env.HR_DOCS_STORAGE
    || (process.env.AWS_BUCKET && process.env.AWS_ACCESS_KEY && process.env.AWS_SECRET_KEY ? "s3" : "local");

let client;
const s3 = () => client || (client = new S3Client({
    region: process.env.AWS_REGION || "ap-south-1",
    credentials: { accessKeyId: process.env.AWS_ACCESS_KEY, secretAccessKey: process.env.AWS_SECRET_KEY },
}));

const localDir = () => path.resolve(process.env.HR_DOCS_DIR || path.join(process.cwd(), "private_uploads", "hr-docs"));
// keys are generated by us ("hr-documents/<employee>/<uuid>.<ext>"); never let one escape the folder
const localPath = (key) => {
    const file = path.resolve(localDir(), key.replace(/^hr-documents\//, ""));
    if (!file.startsWith(localDir() + path.sep)) throw new Error("Bad document key");
    return file;
};

export async function putDoc(storage, key, buffer, mime) {
    if (storage === "s3") {
        await s3().send(new PutObjectCommand({ Bucket: process.env.AWS_BUCKET, Key: key, Body: buffer, ContentType: mime }));
        return;
    }
    const file = localPath(key);
    await fs.promises.mkdir(path.dirname(file), { recursive: true });
    await fs.promises.writeFile(file, buffer);
}

// readable stream of the file
export async function getDoc(storage, key) {
    if (storage === "s3") return (await s3().send(new GetObjectCommand({ Bucket: process.env.AWS_BUCKET, Key: key }))).Body;
    return fs.createReadStream(localPath(key));
}

// best effort: a missing file is not an error
export async function deleteDoc(storage, key) {
    try {
        if (storage === "s3") await s3().send(new DeleteObjectCommand({ Bucket: process.env.AWS_BUCKET, Key: key }));
        else await fs.promises.rm(localPath(key), { force: true });
    } catch (err) {
        console.error("HR document delete failed:", err.message);
    }
}
